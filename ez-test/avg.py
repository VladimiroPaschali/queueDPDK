df = pd.read_csv(StringIO(data), sep=r"\t+")

def empty_poll():
    df_ep = df[df["empty_poll"] > 1000]
    empty_poll_stats = (
        df_ep.groupby("queues")["empty_poll"]
            .agg(mean="mean", std="std", samples="count")
    )

    print("EMPTY POLL")
    print(empty_poll_stats)

def packet_per_burst():
    df_ppb = df[df["packet_per_burst"] > 0]
    ppb_stats = (
        df_ppb.groupby("queues")["packet_per_burst"]
            .agg(mean="mean", std="std", samples="count")
    )

    print("\nPACKET PER BURST")
    print(ppb_stats)

def not_full():
    df_nf = df[df["not_full"] > 1000]
    nf_stats = (
        df_nf.groupby("queues")["not_full"]
            .agg(mean="mean", std="std", samples="count")
    )

    print("\nNOT FULL")
    print(nf_stats)

